library(zutable)
bits <- function(v) vapply(v, function(e) paste(rev(as.character(writeBin(e, raw()))), collapse = ""), "")
g <- c(1, 1, 1)
show <- function(lab, a, b) cat(sprintf("%-34s kernel %s (%s)  base %s (%s)\n", lab, bits(a), format(a), bits(b), format(b)))
for (fn in c("sum", "prod", "mean")) {
  f <- get(fn)
  show(paste(fn, "int NA"), grp_reduce(c(1L, NA, 2L), g, fn, na.rm = FALSE), as.double(f(c(1L, NA, 2L))))
  show(paste(fn, "lgl NA"), grp_reduce(c(TRUE, NA, TRUE), g, fn, na.rm = FALSE), as.double(f(c(TRUE, NA, TRUE))))
  show(paste(fn, "dbl NA"), grp_reduce(c(1, NA, 2), g, fn, na.rm = FALSE), f(c(1, NA, 2)))
  show(paste(fn, "dbl NaN"), grp_reduce(c(1, NaN, 2), g, fn, na.rm = FALSE), f(c(1, NaN, 2)))
  show(paste(fn, "dbl NA,NaN"), grp_reduce(c(1, NA, NaN), g, fn, na.rm = FALSE), f(c(1, NA, NaN)))
  show(paste(fn, "dbl NaN,NA"), grp_reduce(c(1, NaN, NA), g, fn, na.rm = FALSE), f(c(1, NaN, NA)))
  show(paste(fn, "dbl Inf,-Inf"), grp_reduce(c(Inf, -Inf, 1), g, fn, na.rm = FALSE), f(c(Inf, -Inf, 1)))
  show(paste(fn, "dbl Inf,-Inf,NA"), grp_reduce(c(Inf, -Inf, NA), g, fn, na.rm = FALSE), f(c(Inf, -Inf, NA)))
  show(paste(fn, "dbl NA,Inf,-Inf"), grp_reduce(c(NA, Inf, -Inf), g, fn, na.rm = FALSE), f(c(NA, Inf, -Inf)))
  show(paste(fn, "dbl Inf,-Inf narm"), grp_reduce(c(Inf, -Inf, NA), g, fn), f(c(Inf, -Inf, NA), na.rm = TRUE))
  show(paste(fn, "dbl 0*Inf"), grp_reduce(c(0, Inf, NA), g, fn, na.rm = FALSE), f(c(0, Inf, NA)))
}
for (fn in c("min", "max")) { f <- get(fn)
  show(paste(fn, "dbl NA,NaN"), grp_reduce(c(1, NA, NaN), g, fn, na.rm = FALSE), f(c(1, NA, NaN)))
  show(paste(fn, "dbl NaN,NA"), grp_reduce(c(1, NaN, NA), g, fn, na.rm = FALSE), f(c(1, NaN, NA)))
  show(paste(fn, "dbl NaN"), grp_reduce(c(1, NaN, 3), g, fn, na.rm = FALSE), f(c(1, NaN, 3)))
  show(paste(fn, "dbl -0,0"), grp_reduce(c(-0, 0, 0), g, fn), f(c(-0, 0, 0)))
  show(paste(fn, "dbl 0,-0"), grp_reduce(c(0, -0, -0), g, fn), f(c(0, -0, -0)))
}
