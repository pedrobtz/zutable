source("pre.R")
print(Sys.getlocale("LC_CTYPE"))
raw_s <- "caf\xc3\xa9"            # unmarked bytes (what readLines/read.csv give without encoding=)
u <- "café"; l1 <- "caf\xe9"; Encoding(l1) <- "latin1"
x <- try_(zutable(s = raw_s)); print(charToRaw(x$s)); print(Encoding(x$s)); print(identical(charToRaw(x$s), charToRaw(raw_s)))
d <- data.frame(s = raw_s); y <- try_(as_zutable(d)); print(charToRaw(y$s))
z <- zutable(s = c(u, l1, "a")); print(lapply(z$s, charToRaw)); print(Encoding(z$s))
r <- as.data.frame(z[select = .(n = nchar(s), up = upper(s), e = s == u, e1 = s == l1, i = s %in% c(l1), lk = like(s, "caf_"), lk2 = like(s, "%é"), sb = substr(s, 4L, 4L), sw = starts_with(s, "café"))])
print(r[c("n", "e", "e1", "i", "lk", "lk2", "sw")]); print(lapply(r$up, charToRaw)); print(lapply(r$sb, charToRaw))
print(z[order = desc(s)]$s == z$s[order(z$s, decreasing = TRUE, method = "radix")])
z2 <- zutable(s = "a"); z2[, s := l1]; print(charToRaw(z2$s)); z2$s <- raw_s; print(charToRaw(z2$s)); z2[1, "s"] <- l1; print(charToRaw(z2$s))
print(try_(z[s == raw_s]$s))
print(format(schema(e = enum(c(u, "b")))))
e <- zutable(e = factor(c(l1, "b"))); print(lapply(levels(e$e), charToRaw)); print(Encoding(levels(e$e))); print(try_(nrow(e[e == u]))); print(try_(nrow(e[e == l1])))
ee <- zutable(e = factor(c(u, "b"))); print(try_(nrow(join(e, ee, on = e))))
ks <- zutable(k = c(l1, "b"), v = 1:2); ku <- zutable(k = c(u, "b"), w = 3:4); print(nrow(join(ks, ku, on = k)))
cn <- try_(zutable("café" = 1, b = 2)); print(names(cn)); nm <- l1; cn2 <- try_(as_zutable(setNames(list(1, 2), c(l1, "b")))); print(Encoding(names(cn2))); print(try_(cn2[select = .(b)])); print(try_(rbind(cn, cn2)))
print(try_(as_zutable(setNames(list(1, 2), c(l1, u)))))
