cat("--- merge oracle\n")
set.seed(1); a <- data.frame(k = sample(1:5, 20, TRUE), s = sample(c("a","b"), 20, TRUE), av = 1:20); b <- data.frame(k = sample(3:8, 15, TRUE), s = sample(c("a","b","c"), 15, TRUE), bv = 101:115)
for (how in c("inner", "left", "right", "full")) {
  z <- as.data.frame(join(as_zutable(a), as_zutable(b), on = .(k, s), how = how))
  m <- merge(a, b, by = c("k", "s"), all.x = how %in% c("left", "full"), all.y = how %in% c("right", "full"))
  so <- function(d) { d <- d[do.call(order, d), ]; rownames(d) <- NULL; d }
  cat(how, isTRUE(all.equal(so(z), so(m))), "\n")
}
