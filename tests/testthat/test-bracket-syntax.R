test_that("refused forms are syntax errors that show the supported spelling", {
  z <- zutable(a = 1:3, b = c("x", "y", "z"), c = c(1.5, 2, 2.5))
  cnd <- expect_error(z[a > 1, where = b == "x"], class = "zutable_syntax_error")
  expect_match(conditionMessage(cnd), "x[where = cond", fixed = TRUE)
  expect_error(z[, .(a), select = .(b)], class = "zutable_syntax_error")
  expect_error(z[select = .(a), update = b := "q"], class = "zutable_syntax_error")
  expect_error(z[, c * 2], class = "zutable_syntax_error")
  expect_error(z[, .(c * 2)], class = "zutable_syntax_error")
  expect_error(z[, .(a, -b)], class = "zutable_syntax_error")
  expect_error(z[select = a + 1], class = "zutable_syntax_error")
  expect_error(z[limit = -1], class = "zutable_syntax_error")
  expect_error(z[limit = 1.5], class = "zutable_syntax_error")
  expect_error(z[limit = c(1, 2)], class = "zutable_syntax_error")
  expect_error(z[distinct = NA], class = "zutable_syntax_error")
  expect_error(z[, .(b), distinct = TRUE, order = a], class = "zutable_syntax_error")
  expect_error(z[nope = 1], class = "zutable_syntax_error")
  expect_error(z["x", ], class = "zutable_syntax_error")
  expect_error(z[1:2, .(a)], class = "zutable_syntax_error")
  expect_error(z[order = 1], class = "zutable_syntax_error")
})

test_that("refused forms that are type and schema errors", {
  z <- zutable(a = 1:3, b = c("x", "y", "z"), l = list(1L, 2L, 3L))
  expect_error(z[a + 1], class = "zutable_type_error")
  expect_error(z[sum(a) > 1], class = "zutable_type_error")
  expect_error(z[, .(a, a = b)], class = "zutable_schema_error")
  expect_error(z[, .(n = NA)], class = "zutable_type_error")
  expect_error(z[order = l], class = "zutable_type_error")
  expect_error(z[b > 1], class = "zutable_type_error")
})
